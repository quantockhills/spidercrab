// ── Eos Reverb ───────────────────────────────────────────────
//
// A native VST: every parameter reports 0..1 and Eos formats the number
// itself. The module supplies grouping, names and units, and must not invent
// scaling — its frequency controls are plainly not linear.

describe('Eos module', () => {
  const eos = findModule('VST: Eos Reverb')!;
  const controls = eos.panels.flatMap((p) => p.controls);

  /** What the live plugin reports, from tools/fx_dump.js. */
  const EOS_PARAMS = [
    'Predelay', 'Size', 'Decay', 'Attack', 'Diffuse', 'Mod Rate', 'Mod Dpth',
    'Lo Mult', 'Lo Cut', 'Lo Xover', 'Hi Mult', 'Hi Cut', 'Hi Xover',
    'Type', 'Infinite', 'Mix',
  ];

  it('matches the plugin as REAPER names it', () => {
    expect(eos.title).toBe('Eos Reverb');
  });

  it('points every control at a parameter that exists, at the right index', () => {
    for (const c of controls) {
      expect(EOS_PARAMS[c.slider - 1]).toBe(c.expect);
    }
  });

  it('covers every parameter the plugin has', () => {
    const used = new Set(controls.map((c) => c.expect));
    expect(EOS_PARAMS.filter((n) => !used.has(n))).toEqual([]);
  });

  it('surfaces the two Eos hides from its own window', () => {
    // The manual: "tucked them away in a couple of hidden parameters ... not
    // visible in Eos's window".
    for (const name of ['Lo Xover', 'Hi Xover']) {
      expect(controls.some((c) => c.expect === name)).toBe(true);
    }
  });

  it('never rescales a value, since the plugin formats its own', () => {
    // A format function here would be a guess at Eos's mapping. Units only.
    const scaled = controls.filter((c) => 'format' in c && c.format);
    expect(scaled).toEqual([]);
  });

  it('separates the input filters from the tail multipliers', () => {
    // Eos draws them on one graph because they share it, but the cuts act on
    // the way in and the multipliers on the tail.
    const panelOf = (name: string) =>
      eos.panels.find((p) => p.controls.some((c) => c.expect === name))!.label;
    expect(panelOf('Lo Cut')).toBe('Input');
    expect(panelOf('Lo Mult')).toBe('Tail tone');
  });

  it('explains every control', () => {
    expect(controls.filter((c) => !c.help).map((c) => c.label)).toEqual([]);
  });
});

describe('help popover placement', () => {
  function hold(el: Element) {
    fireEvent.pointerDown(el, { clientX: 10, clientY: 10 });
    act(() => { vi.advanceTimersByTime(600); });
  }

  beforeEach(() => vi.useFakeTimers());
  afterEach(() => {
    vi.useRealTimers();
    vi.restoreAllMocks();
  });

  /** Pretend the label sits `fromBottom` pixels above the foot of the window. */
  function placeLabel(fromBottom: number) {
    vi.spyOn(HTMLElement.prototype, 'getBoundingClientRect').mockReturnValue({
      bottom: window.innerHeight - fromBottom, top: 0, left: 0, right: 0,
      width: 0, height: 0, x: 0, y: 0, toJSON: () => ({}),
    } as DOMRect);
  }

  it('drops below the label when there is room', () => {
    placeLabel(400);
    render(<HelpLabel text="Decay" help="How long the tail lasts." />);
    hold(screen.getByText('Decay'));
    expect(screen.getByRole('tooltip').className).toContain('top-full');
  });

  it('flips above when the strip would swallow it', () => {
    // A control near the foot of the device: below is where the navigation
    // strip is, so the explanation would be unreadable there.
    placeLabel(20);
    render(<HelpLabel text="Decay" help="How long the tail lasts." />);
    hold(screen.getByText('Decay'));
    expect(screen.getByRole('tooltip').className).toContain('bottom-full');
  });
});

// ── Distortion, and its curve ────────────────────────────────
//
// The three Cockos waveshapers are all memoryless — output depends only on the
// current input — so the transfer curve can be computed from the parameters
// rather than measured, and the picture is exact.

describe('shape maths', () => {
  const soft = { knee: 0.25, hardness: 6, fuzz: 20, mirror: true, points: [] };

  it('leaves Soft alone below the knee', () => {
    expect(shapeSample(0.1, 0, soft)).toBeCloseTo(0.1);
    expect(shapeSample(-0.2, 0, soft)).toBeCloseTo(-0.2);
  });

  it('bends Soft above the knee without clipping flat', () => {
    // diff/(soft+diff) approaches 1, so it heads for knee+1 rather than a wall.
    const a = shapeSample(0.5, 0, soft);
    const b = shapeSample(0.9, 0, soft);
    expect(a).toBeGreaterThan(0.25);
    expect(a).toBeLessThan(0.5);
    expect(b).toBeGreaterThan(a);
  });

  it('keeps every shape odd-symmetric about zero', () => {
    // An asymmetric curve adds even harmonics, which none of these should do
    // unless the Curve shape is given separate halves.
    for (const shape of [0, 1, 2]) {
      for (const x of [0.15, 0.4, 0.75, 1]) {
        const opts = { ...soft, points: Array.from({ length: 64 }, (_, i) =>
          (i < 32 ? (i + 1) / 32 : -(i - 31) / 32)) };
        expect(shapeSample(-x, shape, opts)).toBeCloseTo(-shapeSample(x, shape, opts), 6);
      }
    }
  });

  it('passes signal through unchanged when the Curve is left at its default', () => {
    // The plugin ships the table tracing y = x, so an untouched Curve is clean.
    const points = Array.from({ length: 64 }, (_, i) =>
      (i < 32 ? (i + 1) / 32 : -(i - 31) / 32));
    for (const x of [0.25, 0.5, 0.75, 1]) {
      expect(shapeSample(x, 2, { ...soft, points })).toBeCloseTo(x, 6);
    }
  });

  it('distorts quiet signal with Fuzz, which is the point of it', () => {
    // Soft leaves a quiet sample alone; Fuzz does not. That difference is why
    // a fuzz pedal doesn't clean up when you play softer.
    const quiet = 0.05;
    expect(shapeSample(quiet, 0, soft)).toBeCloseTo(quiet);
    expect(shapeSample(quiet, 1, soft)).toBeGreaterThan(quiet * 2);
  });
});

